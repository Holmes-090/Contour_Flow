def vector(source, name):
    from qgis.core import QgsVectorLayer

    layer = QgsVectorLayer(source, name, "ogr")
    check(layer.isValid(), f"fixture {name} failed to load from {source}")
    return layer


def raster(source, name):
    from qgis.core import QgsRasterLayer

    layer = QgsRasterLayer(source, name)
    check(layer.isValid(), f"fixture {name} failed to load from {source}")
    return layer


def features(layer):
    return list(layer.getFeatures())


def values(layer):
    return [f["value"] for f in layer.getFeatures()]


def is_multiple(value, interval, tol=1e-6):
    return abs(value / interval - round(value / interval)) < tol


def all_valid(layer):
    bad = [f.id() for f in layer.getFeatures() if not f.geometry().isGeosValid()]
    return bad


def vertices(layer):
    for feature in layer.getFeatures():
        for vertex in feature.geometry().vertices():
            yield feature["value"], vertex.x(), vertex.y()


def boundary_in_utm(ctx, layer, selected_only=False):
    from qgis.core import QgsCoordinateReferenceSystem, QgsCoordinateTransform, QgsGeometry, QgsProject

    transform = QgsCoordinateTransform(layer.crs(), QgsCoordinateReferenceSystem("EPSG:32633"), QgsProject.instance())
    geometries = []
    for feature in (layer.getSelectedFeatures() if selected_only else layer.getFeatures()):
        g = QgsGeometry(feature.geometry())
        g.transform(transform)
        if not g.isGeosValid():
            g = g.makeValid()
        geometries.append(g)
    return QgsGeometry.unaryUnion(geometries)


def request(**kwargs):
    from contour_flow.core.workflow import ContourRequest

    return ContourRequest(**kwargs)


def run(req, **kwargs):
    from contour_flow.core.workflow import run_contour_workflow

    return run_contour_workflow(req, **kwargs)


def points_request(ctx, **kwargs):
    base = dict(point_layer=ctx.points, value_field="elev")
    base.update(kwargs)
    return request(**base)


def expect_error(ctx, req, fragment):
    from contour_flow.core import ContourError

    try:
        run(req)
    except ContourError as exc:
        check(fragment.lower() in str(exc).lower(), f"expected error containing {fragment!r}, got: {exc}")
        return str(exc)
    raise Check(f"expected a ContourError containing {fragment!r}, but the run succeeded")



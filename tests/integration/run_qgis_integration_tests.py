def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", default="")
    parser.add_argument("--fixtures-only", action="store_true")
    parser.add_argument("--output", default=os.path.join(REPO, "tests", "integration_output"))
    args = parser.parse_args()

    global APP
    APP = start_qgis()
    QgsApplication.messageLog().messageReceived.connect(_collect_log)
    from fixtures import create_fixtures
    from osgeo import gdal

    if os.path.isdir(args.output):
        shutil.rmtree(args.output)
    os.makedirs(args.output)
    sources = create_fixtures(os.path.join(args.output, "fixtures"))
    if args.fixtures_only:
        print(f"Fixtures written to {os.path.join(args.output, 'fixtures')}")
        return 0

    ctx = Context(args.output)
    ctx.sources = sources
    ctx.points = vector(sources["points"], "points")
    ctx.raster_path = sources["raster"]
    ctx.raster = raster(sources["raster"], "gradient_dem")

    selected = [(n, f) for n, f in TESTS if not args.only or any(w.lower() in n.lower() for w in args.only.split(","))]
    print("Contour Flow QGIS Integration Tests\n")
    print(f"QGIS: {Qgis.version()}")
    print(f"GDAL: {gdal.__version__}")
    print(f"Python: {sys.version.split()[0]}")
    print(f"Output: {args.output}\n")
    passed = failed = skipped = 0
    failures = []
    for name, function in selected:
        ctx.stage, ctx.details = "", []
        del LOG[:]
        started = time.time()
        try:
            function(ctx)
        except Skip as exc:
            skipped += 1
            print(f"SKIP {name}  ({exc})")
            continue
        except Exception as exc:  # noqa: BLE001 - report every failure
            failed += 1
            print(f"FAIL {name}  ({time.time() - started:.1f}s)")
            failures.append((name, ctx.stage, exc, traceback.format_exc(), list(LOG)))
        else:
            passed += 1
            print(f"PASS {name}  ({time.time() - started:.1f}s)")
            for line in ctx.details:
                print(f"     {line}")
    print(f"\n{passed} passed\n{failed} failed")
    for name, stage, exc, trace, log in failures:
        print(f"\n--- {name} failed at stage: {stage or '(start)'}\n{type(exc).__name__}: {exc}")
        if not isinstance(exc, Check):
            print(trace)
        if log:
            print("QGIS log:\n  " + "\n  ".join(line[:500] for line in log[-15:]))
    return 1 if failed else 0



@test("IDW")
def t_idw(ctx):
    from qgis.core import QgsPointXY

    from contour_flow.core.options import METHOD_IDW, SURFACE_TEMPORARY
    from fixtures import X0, Y0

    samples = {}
    for power in (2.0, 5.0):
        ctx.stage = f"power {power:g}"

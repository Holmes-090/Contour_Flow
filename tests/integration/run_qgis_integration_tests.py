@test("Raster contour")
def t_raster_contour(ctx):
    import processing
    from qgis.core import QgsProcessingFeedback, QgsWkbTypes

    ctx.stage = "raw gdal:contour"
    out = os.path.join(ctx.output, "raw_contour.gpkg")
    result = processing.run("gdal:contour", {"INPUT": ctx.raster, "BAND": 1, "INTERVAL": 2.0,
                                             "FIELD_NAME": "value", "OUTPUT": out}, feedback=QgsProcessingFeedback(False))
    layer = vector(result["OUTPUT"], "raw contours")
    check(QgsWkbTypes.geometryType(layer.wkbType()) == Qgis.GeometryType.Line, "raw output is not a line layer")
    levels = sorted(set(values(layer)))
    check(levels == [52.0 + 2 * i for i in range(9)], f"raw levels {levels}")

    ctx.stage = "workflow, raster, automatic interval"
    plan_req = request(source_type="raster", raster_layer=ctx.raster)
    result = run(plan_req)
    layer = result.contour_layer
    check(result.interval == 2.0, f"automatic interval {result.interval}, expected 2")
    check(layer.fields().names() == ["value", "is_major"], f"fields {layer.fields().names()}")
    levels = sorted(set(values(layer)))
    check(len(levels) == 9 and all(is_multiple(v, 2.0) for v in levels), f"levels {levels}")
    check(not all_valid(layer), f"invalid geometries {all_valid(layer)}")
    # value 50 + 0.1*col at cell centres (col + 0.5 m): level L lies at x = (L - 50)/0.1 + 0.5
    worst = max(abs((x - 500000.0) - ((v - 50.0) / 0.1 + 0.5)) for v, x, _y in vertices(layer))
    check(worst < 0.05, f"contour positions off by up to {worst:.4f} m")
    ctx.note(f"{layer.featureCount()} lines, levels {levels[0]:g}-{levels[-1]:g}, max position error {worst:.2e} m")


def _plane_error(layer):
    from fixtures import X0, Y0, plane

    return max(abs(plane(x - X0, y - Y0) - v) for v, x, y in vertices(layer))



def _inside(layer, polygon, tol=0.01):
    grown = polygon.buffer(tol, 8)
    return [f.id() for f in layer.getFeatures() if not grown.contains(f.geometry())]


@test("Boundary clipping + CRS transform")
def t_boundary(ctx):
    boundary = vector(ctx.sources["boundary_wgs84"], "boundary_wgs84")
    check(boundary.crs().authid() == "EPSG:4326", "boundary fixture is not in WGS84")
    ctx.stage = "WGS84 boundary over UTM points"
    result = run(points_request(ctx, boundary_layer=boundary))
    layer = result.contour_layer
    polygon = boundary_in_utm(ctx, boundary)
    outside = _inside(layer, polygon)
    check(layer.featureCount() > 0, "no contours inside the boundary")
    check(not outside, f"{len(outside)} contour(s) extend outside the boundary")
    check(not all_valid(layer), "invalid geometries after clipping")
    from qgis.core import QgsGeometry

    edge = QgsGeometry(polygon.constGet().boundary())
    ends = []
    for f in layer.getFeatures():
        geometry = f.geometry()
        lines = geometry.asMultiPolyline() if geometry.isMultipart() else [geometry.asPolyline()]
        for line in lines:
            ends += [edge.distance(QgsGeometry.fromPointXY(line[0])), edge.distance(QgsGeometry.fromPointXY(line[-1]))]
    on_edge = sum(1 for d in ends if d < 0.01)
    check(on_edge >= 2, f"only {on_edge} line ends lie on the boundary edge (not clipped?)")

    ctx.stage = "multipart + invalid boundary, all features"
    multi = vector(ctx.sources["boundary_multi"], "boundary_multi")
    from contour_flow.core.workflow import plan_contours

    plan = plan_contours(points_request(ctx, boundary_layer=multi))
    check(any("repaired" in w for w in plan.warnings), f"invalid bow-tie not reported as repaired: {plan.warnings}")
    result = run(points_request(ctx, boundary_layer=multi))
    check(not _inside(result.contour_layer, boundary_in_utm(ctx, multi)), "contours outside the multipart boundary")

    ctx.stage = "selected boundary feature only"
    multi.selectByExpression("\"name\" = 'two parts'")
    result = run(points_request(ctx, boundary_layer=multi, boundary_selected_only=True))
    selected = boundary_in_utm(ctx, multi, selected_only=True)
    check(not _inside(result.contour_layer, selected), "contours outside the selected boundary feature")
    multi.removeSelection()
    ctx.note(f"WGS84 boundary: {layer.featureCount()} clipped lines, all inside, all valid")



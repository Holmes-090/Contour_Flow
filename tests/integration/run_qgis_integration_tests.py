@test("Convex hull + buffer")
def t_buffered_hull(ctx):
    from contour_flow.core.options import EXTENT_BUFFERED_HULL, METHOD_IDW
    from contour_flow.core.workflow import plan_contours
    from fixtures import X0, Y0

    req = points_request(ctx, method=METHOD_IDW, extent_mode=EXTENT_BUFFERED_HULL, buffer_distance=20.0)
    plan = plan_contours(req)
    check(plan.ok, f"plan errors {plan.errors}")
    e = plan.extent
    got = (e.xMinimum() - X0, e.yMinimum() - Y0, e.xMaximum() - X0, e.yMaximum() - Y0)
    pad = 2 * plan.cell_size  # grid padded by two cells around a clip polygon (edge contours)
    expected = (-20 - pad, -20 - pad, 120 + pad, 120 + pad)
    check(all(abs(a - b) < 1e-6 for a, b in zip(got, expected)), f"extent {got}, expected {expected}")
    area = plan.clip_polygon.area()
    exact = 100 * 100 + 4 * 100 * 20 + math.pi * 20 ** 2
    check(abs(area - exact) / exact < 0.01, f"buffered hull area {area:.1f}, expected about {exact:.1f}")
    check(any(w.startswith("IMPORTANT:") and "extrapolates" in w for w in plan.warnings), "no IDW extrapolation warning")
    result = run(req)
    layer = result.contour_layer
    check(not _inside(layer, plan.clip_polygon), "contours outside the buffered hull")
    beyond = max(max(X0 - x, x - (X0 + 100), Y0 - y, y - (Y0 + 100)) for _v, x, y in vertices(layer))
    check(beyond > 10, f"contours reach only {beyond:.1f} m beyond the points")
    check(not all_valid(layer), "invalid geometries")
    got = tuple(round(v, 2) for v in got)
    ctx.note(f"extent {got} (incl. {pad:.2f} m padding), clip area {area:.0f} m2 (exact circle {exact:.0f}), contours reach {beyond:.1f} m beyond hull")


@test("Smoothing")
def t_smoothing(ctx):
    from contour_flow.core.options import METHOD_IDW, SMOOTH_LIGHT, SMOOTH_MEDIUM

    for mode, label in ((SMOOTH_LIGHT, "Light (iterations 1"), (SMOOTH_MEDIUM, "Medium (iterations 2")):
        ctx.stage = mode
        result = run(points_request(ctx, method=METHOD_IDW, smoothing_mode=mode, keep_unsmoothed=True))
        smoothed, unsmoothed = result.contour_layer, result.extra_layers[0]
        check(smoothed.name().endswith("smoothed") and not unsmoothed.name().endswith("smoothed"),
              f"names {smoothed.name()!r} / {unsmoothed.name()!r}")
        check(sorted(values(smoothed)) == sorted(values(unsmoothed)), "smoothing changed the value attributes")
        n_s = sum(1 for _ in vertices(smoothed))
        n_u = sum(1 for _ in vertices(unsmoothed))
        check(n_s > n_u, f"smoothed has {n_s} vertices, unsmoothed {n_u}")
        check(not all_valid(smoothed), "smoothing produced invalid geometry")
        meta = dict(json.loads(smoothed.customProperty("contour_flow/metadata"))["settings"])
        check(meta["Smoothing"].startswith(label) and meta["Smoothed geometry"] is True, f"metadata {meta['Smoothing']}")
        meta_u = dict(json.loads(unsmoothed.customProperty("contour_flow/metadata"))["settings"])
        check(meta_u["Smoothed geometry"] is False, "unsmoothed copy marked as smoothed")
        ctx.note(f"{mode}: {n_u} -> {n_s} vertices, values unchanged")


